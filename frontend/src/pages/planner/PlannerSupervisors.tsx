import './PlannerV2.css';
import React, { useCallback, useEffect, useState } from 'react';
import { Header } from '../../components/common/Header';
import { Sidebar } from '../../components/common/Sidebar';
import {
  createPlannerSupervisor,
  listMyAssignments,
  listMyBaselines,
  type CreatedSupervisor,
  type PlannerSupervisorAssignment,
  type ScheduleBaseline,
} from '../../lib/plannerSupervisors';

export const PlannerSupervisors: React.FC = () => {
  const [baselines, setBaselines] = useState<ScheduleBaseline[]>([]);
  const [assignments, setAssignments] = useState<PlannerSupervisorAssignment[]>([]);
  const [setupError, setSetupError] = useState('');
  const [loading, setLoading] = useState(true);
  const [name, setName] = useState('');
  const [email, setEmail] = useState('');
  const [baselineId, setBaselineId] = useState('');
  const [creating, setCreating] = useState(false);
  const [formError, setFormError] = useState('');
  const [created, setCreated] = useState<CreatedSupervisor | null>(null);
  const [copied, setCopied] = useState('');

  const refresh = useCallback(async () => {
    setLoading(true);
    setSetupError('');
    try {
      const [loadedBaselines, loadedAssignments] = await Promise.all([
        listMyBaselines(),
        listMyAssignments(),
      ]);
      setBaselines(loadedBaselines);
      setAssignments(loadedAssignments);
      if (!baselineId) {
        const sample = loadedBaselines.find((b) => b.is_sample);
        if (sample) setBaselineId(sample.id);
        else if (loadedBaselines[0]) setBaselineId(loadedBaselines[0].id);
      }
    } catch (err) {
      setSetupError(err instanceof Error ? err.message : 'Could not load supervisors.');
    } finally {
      setLoading(false);
    }
  }, [baselineId]);

  useEffect(() => {
    void refresh();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const handleCreate = async (e: React.FormEvent) => {
    e.preventDefault();
    setFormError('');
    setCreated(null);
    setCreating(true);
    try {
      const result = await createPlannerSupervisor({
        supervisorName: name,
        workEmail: email,
        baselineId,
      });
      setCreated(result);
      setName('');
      setEmail('');
      await refresh();
    } catch (err) {
      setFormError(err instanceof Error ? err.message : 'Could not create this supervisor.');
    } finally {
      setCreating(false);
    }
  };

  const copy = async (value: string, label: string) => {
    try {
      await navigator.clipboard.writeText(value);
      setCopied(label);
    } catch {
      setCopied('');
    }
  };

  return (
    <div className="setu-planner-v2 min-h-screen bg-setu-slate-100 flex flex-col">
      <Header currentRole="planner" />
      <div className="flex-1 flex flex-col md:flex-row">
        <Sidebar />
        <main className="flex-1 min-w-0 p-4 sm:p-6 lg:p-8 space-y-5 max-w-[90rem]">
          <section className="border-l-4 border-[#007AFF] bg-white px-5 py-5 sm:px-6 sm:py-6 shadow-xs">
            <p className="text-xs font-semibold tracking-[0.14em] text-[#007AFF] uppercase">
              Planner workspace
            </p>
            <h1 className="mt-1 text-2xl sm:text-3xl font-extrabold tracking-tight text-setu-slate-900">
              Supervisors
            </h1>
            <p className="mt-1 max-w-2xl text-sm leading-6 text-setu-slate-600">
              Add a supervisor to one schedule baseline. That supervisor sees
              only that baseline — never another planner&apos;s schedule.
              The Sample Baseline is demo data only, not a live project.
            </p>
          </section>

          {setupError && (
            <section className="rounded-xl border border-amber-200 bg-amber-50 p-4 text-sm text-amber-900">
              {setupError}
            </section>
          )}

          <section className="rounded-xl border border-setu-slate-200 bg-white p-5 sm:p-6 shadow-xs">
            <h2 className="text-base font-bold text-setu-slate-900">Add supervisor</h2>
            <p className="mt-1 text-sm text-setu-slate-600">
              The supervisor&apos;s credentials are generated by the server and
              shown once below. Share them securely — they will not be shown again.
            </p>
            <form onSubmit={handleCreate} className="mt-4 space-y-4">
              <div>
                <label htmlFor="supervisor-name" className="text-sm font-medium text-setu-slate-800">
                  Supervisor name
                </label>
                <input
                  id="supervisor-name"
                  type="text"
                  value={name}
                  onChange={(e) => setName(e.target.value)}
                  placeholder="e.g. Demo Supervisor"
                  className="mt-1 w-full rounded-lg border border-setu-slate-300 px-3 py-2.5 text-sm focus:outline-none focus:ring-2 focus:ring-[#007AFF]/30"
                />
              </div>
              <div>
                <label htmlFor="supervisor-email" className="text-sm font-medium text-setu-slate-800">
                  Work email
                </label>
                <input
                  id="supervisor-email"
                  type="email"
                  value={email}
                  onChange={(e) => setEmail(e.target.value)}
                  placeholder="name@company.com"
                  className="mt-1 w-full rounded-lg border border-setu-slate-300 px-3 py-2.5 text-sm focus:outline-none focus:ring-2 focus:ring-[#007AFF]/30"
                />
              </div>
              <div>
                <label htmlFor="supervisor-baseline" className="text-sm font-medium text-setu-slate-800">
                  Schedule baseline
                </label>
                <select
                  id="supervisor-baseline"
                  value={baselineId}
                  onChange={(e) => setBaselineId(e.target.value)}
                  className="mt-1 w-full rounded-lg border border-setu-slate-300 px-3 py-2.5 text-sm focus:outline-none focus:ring-2 focus:ring-[#007AFF]/30"
                >
                  {baselines.length === 0 && <option value="">Sample Baseline (demo only)</option>}
                  {baselines.map((b) => (
                    <option key={b.id} value={b.id}>
                      {b.name}
                      {b.is_sample ? ' (demo only)' : ''}
                    </option>
                  ))}
                </select>
              </div>
              {formError && (
                <p className="rounded-lg border border-rose-200 bg-rose-50 p-3 text-sm text-rose-900">
                  {formError}
                </p>
              )}
              <button
                type="submit"
                disabled={creating || loading || baselines.length === 0}
                className="rounded-xl bg-[#007AFF] px-5 py-2.5 text-sm font-semibold text-white disabled:opacity-50"
              >
                {creating ? 'Creating…' : 'Create supervisor'}
              </button>
            </form>

            {created && (
              <div className="mt-5 rounded-xl border border-emerald-200 bg-emerald-50 p-4">
                <p className="text-sm font-bold text-emerald-900">
                  Supervisor created for {created.baseline_name}
                  {created.is_sample ? ' (demo only)' : ''}. Share these credentials
                  securely now — they will not be shown again.
                </p>
                <div className="mt-3 space-y-2 text-sm">
                  <div className="flex flex-wrap items-center gap-2">
                    <span className="font-medium">Email:</span>
                    <code className="break-all">{created.email}</code>
                    <button type="button" onClick={() => void copy(created.email, 'email')} className="text-[#007AFF] font-semibold">
                      Copy
                    </button>
                  </div>
                  <div className="flex flex-wrap items-center gap-2">
                    <span className="font-medium">Password:</span>
                    <code className="break-all">{created.password}</code>
                    <button type="button" onClick={() => void copy(created.password, 'password')} className="text-[#007AFF] font-semibold">
                      Copy
                    </button>
                  </div>
                </div>
                {copied && <p className="mt-2 text-xs text-emerald-800">Copied {copied}.</p>}
                <button
                  type="button"
                  onClick={() => setCreated(null)}
                  className="mt-3 text-sm font-semibold text-setu-slate-700"
                >
                  Done — hide credentials
                </button>
              </div>
            )}
          </section>

          <section className="rounded-xl border border-setu-slate-200 bg-white p-5 sm:p-6 shadow-xs">
            <h2 className="text-base font-bold text-setu-slate-900">My assigned supervisors</h2>
            <p className="mt-1 text-sm text-setu-slate-600">
              Passwords are never listed here. If a supervisor loses their
              credentials, create a fresh account for them — do not reuse an old password.
            </p>
            {loading ? (
              <p className="mt-3 text-sm text-setu-slate-500">Loading assignments…</p>
            ) : assignments.length === 0 ? (
              <p className="mt-3 text-sm text-setu-slate-500">
                No supervisors assigned yet.
              </p>
            ) : (
              <ul className="mt-3 divide-y divide-setu-slate-100">
                {assignments.map((a) => (
                  <li key={a.id} className="py-3 text-sm">
                    <span className="font-medium text-setu-slate-900">
                      Supervisor {a.supervisor_id.slice(0, 8)}…
                    </span>
                    <span className="text-setu-slate-600">
                      {' '}· {a.schedule_baselines?.name || 'Baseline'}
                      {a.schedule_baselines?.is_sample ? ' (demo only)' : ''}
                    </span>
                    {a.created_at && (
                      <span className="block text-xs text-setu-slate-500">
                        Added {new Date(a.created_at).toLocaleDateString()}
                      </span>
                    )}
                  </li>
                ))}
              </ul>
            )}
          </section>
        </main>
      </div>
    </div>
  );
};
